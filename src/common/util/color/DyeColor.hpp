#pragma once

#include "core/Types.hpp"

namespace mc {

/**
 * @brief 染料颜色枚举
 *
 * 对应 MC 1.16.5 DyeColor，定义16种标准染料颜色。
 * 广泛用于旗帜、皮革盔甲染色、混凝土、陶瓦等场景。
 */
enum class DyeColor : u8 {
    White = 0,
    Orange = 1,
    Magenta = 2,
    LightBlue = 3,
    Yellow = 4,
    Lime = 5,
    Pink = 6,
    Gray = 7,
    LightGray = 8,
    Cyan = 9,
    Purple = 10,
    Blue = 11,
    Brown = 12,
    Green = 13,
    Red = 14,
    Black = 15,
    Count = 16
};

} // namespace mc
