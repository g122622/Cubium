/**
 * chat_formatting.ts — `ChatFormatting` 格式码能力的输入构造。
 *
 * 单元形如 `<模式>|<参数…>`，由探针与 oracle 的 `list` 各自枚举同一张表。
 */

/** 格式码能力的一个单元。 */
export interface ChatFormattingUnit {
    readonly unit: string;
}

/**
 * 单元字符串原样透传。
 *
 * `§` 以字面 UTF-8 字符进入单元字符串；JSON 能直接承载它，两侧解析后一致。
 */
export function chatFormattingInput(unit: string): ChatFormattingUnit {
    return { unit };
}